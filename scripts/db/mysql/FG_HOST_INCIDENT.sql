-- 主机未关闭告警。持续时长、确认和升级由主机监控维护，发送时再写预警日志。
CREATE TABLE IF NOT EXISTS `FG_HOST_INCIDENT` (
  `tenantId` VARCHAR(32) NOT NULL COMMENT '租户ID，联合主键',
  `incidentId` VARCHAR(32) NOT NULL COMMENT '记录ID，联合主键',
  `ruleId` VARCHAR(32) NOT NULL COMMENT '规则ID',
  `agentId` VARCHAR(32) NOT NULL COMMENT '代理ID',
  `hostName` VARCHAR(100) DEFAULT NULL COMMENT '主机名',
  `metricCode` VARCHAR(64) NOT NULL COMMENT '指标编码',
  `levelCode` VARCHAR(16) NOT NULL COMMENT '级别',
  `statusCode` VARCHAR(16) NOT NULL COMMENT '状态：pending、firing、acked、resolved',
  `currentValue` DECIMAL(18, 3) NOT NULL DEFAULT 0 COMMENT '当前值',
  `thresholdValue` DECIMAL(18, 3) NOT NULL DEFAULT 0 COMMENT '阈值',
  `compareOp` VARCHAR(8) NOT NULL COMMENT '比较符',
  `firstFireTime` DATETIME NOT NULL COMMENT '首次触发时间',
  `lastFireTime` DATETIME NOT NULL COMMENT '最近触发时间',
  `resolveTime` DATETIME DEFAULT NULL COMMENT '恢复时间',
  `ackTime` DATETIME DEFAULT NULL COMMENT '确认时间',
  `ackWho` VARCHAR(32) DEFAULT NULL COMMENT '确认人',
  `messageText` VARCHAR(500) DEFAULT NULL COMMENT '说明',
  `notifiedFlag` VARCHAR(1) NOT NULL DEFAULT 'N' COMMENT '是否已写触发日志(Y已写,N未写)',
  `escalateFlag` VARCHAR(1) NOT NULL DEFAULT 'N' COMMENT '是否已写升级日志(Y已写,N未写)',
  `addTime` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `addWho` VARCHAR(32) NOT NULL COMMENT '创建人ID',
  `editTime` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '最后修改时间',
  `editWho` VARCHAR(32) NOT NULL COMMENT '最后修改人ID',
  `oprSeqFlag` VARCHAR(32) NOT NULL COMMENT '操作序列标识',
  `currentVersion` INT NOT NULL DEFAULT 1 COMMENT '当前版本号',
  `activeFlag` VARCHAR(1) NOT NULL DEFAULT 'Y' COMMENT '活动状态标记(N非活动,Y活动)',
  `noteText` VARCHAR(500) DEFAULT NULL COMMENT '备注信息',
  `extProperty` TEXT DEFAULT NULL COMMENT '扩展属性，JSON格式',
  `reserved1` VARCHAR(64) DEFAULT NULL COMMENT '预留字段1',
  `reserved2` VARCHAR(64) DEFAULT NULL COMMENT '预留字段2',
  `reserved3` VARCHAR(100) DEFAULT NULL COMMENT '预留字段3',
  `reserved4` VARCHAR(100) DEFAULT NULL COMMENT '预留字段4',
  `reserved5` VARCHAR(255) DEFAULT NULL COMMENT '预留字段5',
  PRIMARY KEY (`tenantId`, `incidentId`),
  KEY `IDX_FG_HOST_INCIDENT_OPEN` (`tenantId`, `ruleId`, `agentId`, `statusCode`),
  KEY `IDX_FG_HOST_INCIDENT_ADD` (`tenantId`, `addTime`)
) ENGINE=InnoDB COMMENT='主机未关闭告警';
