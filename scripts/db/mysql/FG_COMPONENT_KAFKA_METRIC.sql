CREATE TABLE IF NOT EXISTS `FG_COMPONENT_KAFKA_METRIC` (
  `tenantId` VARCHAR(32) NOT NULL COMMENT '租户ID，联合主键',
  `pointId` VARCHAR(32) NOT NULL COMMENT '记录ID，联合主键',
  `componentId` VARCHAR(32) NOT NULL COMMENT '连接ID',
  `upFlag` VARCHAR(1) NOT NULL DEFAULT 'N' COMMENT '连通标记(Y连通,N不通)',
  `versionText` VARCHAR(64) DEFAULT NULL COMMENT '版本',
  `roleName` VARCHAR(32) DEFAULT NULL COMMENT '角色',
  `errorText` VARCHAR(100) DEFAULT NULL COMMENT '失败说明',
  `summaryText` VARCHAR(100) DEFAULT NULL COMMENT '摘要',
  `observedTime` DATETIME NOT NULL COMMENT '观测时间',
  `brokerCount` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT 'Broker 数',
  `onlineBrokers` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '可达 Broker',
  `offlineBrokers` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '不可达 Broker',
  `offlinePartitions` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '离线分区',
  `underReplicated` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '未同步分区',
  `preferredReplicas` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '未在首选副本上的分区',
  `underMinIsr` DECIMAL(20, 3) NOT NULL DEFAULT -1 COMMENT '低于最小同步副本的在线分区，未知为 -1',
  `topicCount` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '业务 Topic 数',
  `groupCount` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '消费组数',
  `rebalanceGroups` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '再均衡中的消费组',
  `maxLag` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '最大分区延迟',
  `totalLag` DECIMAL(20, 3) NOT NULL DEFAULT -1 COMMENT '分区延迟合计，未知为 -1',
  `logBytes` DECIMAL(20, 3) NOT NULL DEFAULT -1 COMMENT '日志目录占用字节，未知为 -1',
  `addTime` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `addWho` VARCHAR(32) NOT NULL COMMENT '创建人ID',
  `editTime` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '最后修改时间',
  `editWho` VARCHAR(32) NOT NULL COMMENT '最后修改人ID',
  `oprSeqFlag` VARCHAR(32) NOT NULL COMMENT '操作序列标识',
  `currentVersion` INT NOT NULL DEFAULT 1 COMMENT '当前版本号',
  `activeFlag` VARCHAR(1) NOT NULL DEFAULT 'Y' COMMENT '活动状态标记(N非活动,Y活动)',
  `noteText` VARCHAR(500) DEFAULT NULL COMMENT '备注信息',
  `extProperty` TEXT DEFAULT NULL COMMENT '扩展属性，JSON格式',
  `reserved1` VARCHAR(64) DEFAULT NULL COMMENT '预留字段1',
  `reserved2` VARCHAR(64) DEFAULT NULL COMMENT '预留字段2',
  `reserved3` VARCHAR(100) DEFAULT NULL COMMENT '预留字段3',
  `reserved4` VARCHAR(100) DEFAULT NULL COMMENT '预留字段4',
  `reserved5` VARCHAR(255) DEFAULT NULL COMMENT '预留字段5',
  PRIMARY KEY (`tenantId`, `pointId`),
  KEY `IDX_FG_COMPONENT_KAFKA_METRIC_TIME` (`tenantId`, `componentId`, `observedTime`),
  KEY `IDX_FG_COMPONENT_KAFKA_METRIC_ADD` (`tenantId`, `addTime`)
) ENGINE=InnoDB COMMENT='Kafka采集记录表';

