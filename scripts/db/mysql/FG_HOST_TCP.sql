-- 传输层连接滚动记录。每次上报只插入，供曲线查询。网卡字节流量在 FG_HOST_NET。
CREATE TABLE IF NOT EXISTS `FG_HOST_TCP` (
  `agentId` VARCHAR(32) NOT NULL COMMENT '代理ID',
  `tenantId` VARCHAR(32) NOT NULL COMMENT '租户ID，联合主键',
  `pointId` VARCHAR(32) NOT NULL COMMENT '记录ID，联合主键',
  `batchId` VARCHAR(64) NOT NULL COMMENT '批次号',
  `establishedCount` BIGINT NOT NULL DEFAULT 0 COMMENT 'ESTABLISHED 连接数',
  `listenCount` BIGINT NOT NULL DEFAULT 0 COMMENT 'LISTEN 套接字数',
  `timeWaitCount` BIGINT NOT NULL DEFAULT 0 COMMENT 'TIME_WAIT 连接数',
  `closeWaitCount` BIGINT NOT NULL DEFAULT 0 COMMENT 'CLOSE_WAIT 连接数',
  `synSentCount` BIGINT NOT NULL DEFAULT 0 COMMENT 'SYN_SENT 连接数',
  `synRecvCount` BIGINT NOT NULL DEFAULT 0 COMMENT 'SYN_RECV 连接数',
  `finWaitCount` BIGINT NOT NULL DEFAULT 0 COMMENT 'FIN_WAIT 连接数',
  `lastAckCount` BIGINT NOT NULL DEFAULT 0 COMMENT 'LAST_ACK 连接数',
  `closingCount` BIGINT NOT NULL DEFAULT 0 COMMENT 'CLOSING 连接数',
  `tcpInUseCount` BIGINT NOT NULL DEFAULT 0 COMMENT 'TCP 占用套接字数',
  `udpInUseCount` BIGINT NOT NULL DEFAULT 0 COMMENT 'UDP 占用套接字数',
  `retransmitCount` BIGINT NOT NULL DEFAULT 0 COMMENT '累计重传段数',
  `observedTime` DATETIME NOT NULL COMMENT '观测时间',
  `addTime` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `addWho` VARCHAR(32) NOT NULL COMMENT '创建人ID',
  `editTime` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '最后修改时间',
  `editWho` VARCHAR(32) NOT NULL COMMENT '最后修改人ID',
  `oprSeqFlag` VARCHAR(32) NOT NULL COMMENT '操作序列标识',
  `currentVersion` INT NOT NULL DEFAULT 1 COMMENT '当前版本号',
  `activeFlag` VARCHAR(1) NOT NULL DEFAULT 'Y' COMMENT '活动状态标记(N非活动,Y活动)',
  `noteText` VARCHAR(500) DEFAULT NULL COMMENT '备注信息',
  `extProperty` TEXT DEFAULT NULL COMMENT '扩展属性，JSON格式',
  `reserved1` VARCHAR(64) DEFAULT NULL COMMENT '预留字段1',
  `reserved2` VARCHAR(64) DEFAULT NULL COMMENT '预留字段2',
  `reserved3` VARCHAR(100) DEFAULT NULL COMMENT '预留字段3',
  `reserved4` VARCHAR(100) DEFAULT NULL COMMENT '预留字段4',
  `reserved5` VARCHAR(255) DEFAULT NULL COMMENT '预留字段5',
  PRIMARY KEY (`tenantId`, `pointId`),
  KEY `IDX_FG_HOST_TCP_TIME` (`tenantId`, `agentId`, `observedTime`),
  KEY `IDX_FG_HOST_TCP_ADD` (`tenantId`, `addTime`)
) ENGINE=InnoDB COMMENT='主机传输层连接记录表';
