CREATE TABLE IF NOT EXISTS `FG_AUTH_AUDIT_LOG` (
  `auditId` VARCHAR(32) NOT NULL COMMENT '审计ID，联合主键',
  `tenantId` VARCHAR(32) NOT NULL COMMENT '租户ID，联合主键',
  `userId` VARCHAR(32) NOT NULL COMMENT '操作人用户ID',
  `userName` VARCHAR(100) DEFAULT NULL COMMENT '操作人用户名',
  `action` VARCHAR(32) NOT NULL COMMENT '动作：CREATE/UPDATE/DELETE/GRANT/COMMAND/LOGIN/LOGIN_FAIL/LOGOUT',
  `moduleCode` VARCHAR(64) DEFAULT NULL COMMENT '模块编码，如 fg0002；登录为 login',
  `targetType` VARCHAR(32) DEFAULT NULL COMMENT '目标类型：USER/ROLE/AGENT/SETTING/RULE/CHANNEL/EVENT',
  `targetId` VARCHAR(128) DEFAULT NULL COMMENT '目标业务主键',
  `targetName` VARCHAR(255) DEFAULT NULL COMMENT '目标显示名',
  `resourceCode` VARCHAR(128) DEFAULT NULL COMMENT '权限资源编码',
  `requestPath` VARCHAR(255) DEFAULT NULL COMMENT '请求路径',
  `requestMethod` VARCHAR(16) DEFAULT NULL COMMENT 'HTTP 方法',
  `clientIP` VARCHAR(128) DEFAULT NULL COMMENT '客户端 IP',
  `resultFlag` VARCHAR(1) NOT NULL DEFAULT 'Y' COMMENT '结果：Y成功，N失败',
  `detailText` TEXT DEFAULT NULL COMMENT '操作说明，由业务模块写入',
  `failReason` VARCHAR(500) DEFAULT NULL COMMENT '失败原因，与 resultFlag 分列；成功为空',
  `addTime` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `addWho` VARCHAR(32) NOT NULL COMMENT '创建人ID',
  `editTime` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '最后修改时间',
  `editWho` VARCHAR(32) NOT NULL COMMENT '最后修改人ID',
  `oprSeqFlag` VARCHAR(32) NOT NULL COMMENT '操作序列标识',
  `currentVersion` INT NOT NULL DEFAULT 1 COMMENT '当前版本号',
  `activeFlag` VARCHAR(1) NOT NULL DEFAULT 'Y' COMMENT '活动状态标记(N非活动,Y活动)',
  `noteText` VARCHAR(500) DEFAULT NULL COMMENT '备注信息',
  `extProperty` TEXT DEFAULT NULL COMMENT '扩展属性，JSON格式',
  `reserved1` VARCHAR(64) DEFAULT NULL COMMENT '预留字段1',
  `reserved2` VARCHAR(64) DEFAULT NULL COMMENT '预留字段2',
  `reserved3` VARCHAR(100) DEFAULT NULL COMMENT '预留字段3',
  `reserved4` VARCHAR(100) DEFAULT NULL COMMENT '预留字段4',
  `reserved5` VARCHAR(255) DEFAULT NULL COMMENT '预留字段5',
  PRIMARY KEY (`tenantId`, `auditId`),
  KEY `IDX_FG_AUDIT_TIME` (`tenantId`, `addTime`),
  KEY `IDX_FG_AUDIT_USER` (`tenantId`, `userId`, `addTime`),
  KEY `IDX_FG_AUDIT_MODULE` (`tenantId`, `moduleCode`, `addTime`),
  KEY `IDX_FG_AUDIT_ACTION` (`tenantId`, `action`, `addTime`),
  KEY `IDX_FG_AUDIT_RESULT` (`tenantId`, `resultFlag`, `addTime`),
  KEY `IDX_FG_AUDIT_TARGET` (`tenantId`, `targetType`, `targetId`)
) ENGINE=InnoDB COMMENT='权限审计表';
