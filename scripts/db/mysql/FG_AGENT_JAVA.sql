-- 一个 Java 代理的当前身份。每次上报更新同一行。堆、GC 等曲线另表只插入。
CREATE TABLE IF NOT EXISTS `FG_AGENT_JAVA` (
  `agentId` VARCHAR(32) NOT NULL COMMENT '代理ID，联合主键',
  `tenantId` VARCHAR(32) NOT NULL COMMENT '租户ID，联合主键',
  `appName` VARCHAR(100) NOT NULL COMMENT '应用名称',
  `mainClass` VARCHAR(255) DEFAULT NULL COMMENT '主类',
  `processId` VARCHAR(32) DEFAULT NULL COMMENT '进程号',
  `javaVersion` VARCHAR(64) DEFAULT NULL COMMENT 'Java 版本',
  `startTime` DATETIME DEFAULT NULL COMMENT '进程启动时间',
  `hostName` VARCHAR(100) DEFAULT NULL COMMENT '主机名',
  `ipAddress` VARCHAR(128) DEFAULT NULL COMMENT 'IP 地址',
  `reportedTime` DATETIME NOT NULL COMMENT '最近一次上报时间',
  `heapUsedPercent` DECIMAL(8, 3) NOT NULL DEFAULT 0 COMMENT '当前堆使用率，百分比',
  `heapUsedBytes` BIGINT NOT NULL DEFAULT 0 COMMENT '当前堆已用，字节',
  `heapMaxBytes` BIGINT NOT NULL DEFAULT 0 COMMENT '当前堆上限，字节',
  `nonHeapUsedBytes` BIGINT NOT NULL DEFAULT 0 COMMENT '当前非堆已用，字节',
  `threadCount` BIGINT NOT NULL DEFAULT 0 COMMENT '当前线程数',
  `daemonCount` BIGINT NOT NULL DEFAULT 0 COMMENT '当前守护线程数',
  `collectionCount` BIGINT NOT NULL DEFAULT 0 COMMENT '当前回收累计次数',
  `collectionTimeMs` BIGINT NOT NULL DEFAULT 0 COMMENT '当前回收累计耗时，毫秒',
  `addTime` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `addWho` VARCHAR(32) NOT NULL COMMENT '创建人ID',
  `editTime` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '最后修改时间',
  `editWho` VARCHAR(32) NOT NULL COMMENT '最后修改人ID',
  `oprSeqFlag` VARCHAR(32) NOT NULL COMMENT '操作序列标识',
  `currentVersion` INT NOT NULL DEFAULT 1 COMMENT '当前版本号',
  `activeFlag` VARCHAR(1) NOT NULL DEFAULT 'Y' COMMENT '活动状态标记(N非活动,Y活动)',
  `noteText` VARCHAR(500) DEFAULT NULL COMMENT '备注信息',
  `extProperty` TEXT DEFAULT NULL COMMENT '扩展属性，JSON格式',
  `reserved1` VARCHAR(64) DEFAULT NULL COMMENT '预留字段1',
  `reserved2` VARCHAR(64) DEFAULT NULL COMMENT '预留字段2',
  `reserved3` VARCHAR(100) DEFAULT NULL COMMENT '预留字段3',
  `reserved4` VARCHAR(100) DEFAULT NULL COMMENT '预留字段4',
  `reserved5` VARCHAR(255) DEFAULT NULL COMMENT '预留字段5',
  PRIMARY KEY (`tenantId`, `agentId`),
  KEY `IDX_FG_AGENT_JAVA_NAME` (`tenantId`, `appName`),
  KEY `IDX_FG_AGENT_JAVA_ADD` (`tenantId`, `addTime`)
) ENGINE=InnoDB COMMENT='Java代理身份表';
ALTER TABLE `FG_AGENT_JAVA` ADD COLUMN `rssBytes` BIGINT NOT NULL DEFAULT -1 COMMENT '当前进程常驻内存，字节；读不到为 -1';
