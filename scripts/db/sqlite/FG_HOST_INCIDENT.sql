-- 主机未关闭告警。持续时长、确认和升级由主机监控维护，发送时再写预警日志。
CREATE TABLE IF NOT EXISTS FG_HOST_INCIDENT (
  tenantId TEXT NOT NULL,
  incidentId TEXT NOT NULL,
  ruleId TEXT NOT NULL,
  agentId TEXT NOT NULL,
  hostName TEXT,
  metricCode TEXT NOT NULL,
  levelCode TEXT NOT NULL,
  statusCode TEXT NOT NULL,
  currentValue REAL NOT NULL DEFAULT 0,
  thresholdValue REAL NOT NULL DEFAULT 0,
  compareOp TEXT NOT NULL,
  firstFireTime TEXT NOT NULL,
  lastFireTime TEXT NOT NULL,
  resolveTime TEXT,
  ackTime TEXT,
  ackWho TEXT,
  messageText TEXT,
  notifiedFlag TEXT NOT NULL DEFAULT 'N',
  escalateFlag TEXT NOT NULL DEFAULT 'N',
  addTime TEXT NOT NULL DEFAULT (datetime('now')),
  addWho TEXT NOT NULL,
  editTime TEXT NOT NULL DEFAULT (datetime('now')),
  editWho TEXT NOT NULL,
  oprSeqFlag TEXT NOT NULL,
  currentVersion INTEGER NOT NULL DEFAULT 1,
  activeFlag TEXT NOT NULL DEFAULT 'Y',
  noteText TEXT,
  extProperty TEXT,
  reserved1 TEXT,
  reserved2 TEXT,
  reserved3 TEXT,
  reserved4 TEXT,
  reserved5 TEXT,
  PRIMARY KEY (tenantId, incidentId)
);
CREATE INDEX IF NOT EXISTS IDX_FG_HOST_INCIDENT_OPEN ON FG_HOST_INCIDENT(tenantId, ruleId, agentId, statusCode);
CREATE INDEX IF NOT EXISTS IDX_FG_HOST_INCIDENT_ADD ON FG_HOST_INCIDENT(tenantId, addTime);
