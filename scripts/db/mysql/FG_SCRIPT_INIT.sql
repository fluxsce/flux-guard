-- 种子只执行一次。有 scriptName = seed 且 executionStatus = SUCCESS 的记录后，启动不再灌开发账号和初始授权。
-- 字段对齐 gateway 的 HUB_SCRIPT_EXECUTION_HISTORY：执行结果、失败原因、耗时和语句数。
CREATE TABLE IF NOT EXISTS `FG_SCRIPT_INIT` (
  `initId` VARCHAR(32) NOT NULL COMMENT '初始化记录ID，联合主键',
  `tenantId` VARCHAR(32) NOT NULL COMMENT '租户ID，联合主键',
  `scriptName` VARCHAR(255) NOT NULL COMMENT '脚本名称',
  `scriptPath` VARCHAR(500) NOT NULL COMMENT '脚本路径',
  `scriptVersion` VARCHAR(32) NOT NULL COMMENT '脚本版本',
  `databaseDriver` VARCHAR(50) NOT NULL COMMENT '数据库驱动',
  `executionStatus` VARCHAR(20) NOT NULL COMMENT '执行结果：SUCCESS成功，FAILED失败，SKIPPED跳过',
  `executionTime` DATETIME NOT NULL COMMENT '执行时间',
  `executionDuration` BIGINT NOT NULL DEFAULT 0 COMMENT '执行耗时，毫秒',
  `statementsExecuted` INT NOT NULL DEFAULT 0 COMMENT '成功执行的语句数',
  `errorMessage` TEXT DEFAULT NULL COMMENT '失败原因',
  `addTime` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `addWho` VARCHAR(32) NOT NULL COMMENT '创建人ID',
  `editTime` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '最后修改时间',
  `editWho` VARCHAR(32) NOT NULL COMMENT '最后修改人ID',
  `oprSeqFlag` VARCHAR(32) NOT NULL COMMENT '操作序列标识',
  `currentVersion` INT NOT NULL DEFAULT 1 COMMENT '当前版本号',
  `activeFlag` VARCHAR(1) NOT NULL DEFAULT 'Y' COMMENT '活动状态标记(N非活动,Y活动)',
  `noteText` VARCHAR(500) DEFAULT NULL COMMENT '备注信息',
  `extProperty` TEXT DEFAULT NULL COMMENT '扩展属性，JSON格式',
  `reserved1` VARCHAR(64) DEFAULT NULL COMMENT '预留字段1',
  `reserved2` VARCHAR(64) DEFAULT NULL COMMENT '预留字段2',
  `reserved3` VARCHAR(100) DEFAULT NULL COMMENT '预留字段3',
  `reserved4` VARCHAR(100) DEFAULT NULL COMMENT '预留字段4',
  `reserved5` VARCHAR(255) DEFAULT NULL COMMENT '预留字段5',
  PRIMARY KEY (`tenantId`, `initId`),
  UNIQUE KEY `UK_FG_SCRIPT_INIT` (`tenantId`, `scriptName`, `scriptVersion`, `databaseDriver`),
  KEY `IDX_FG_SCRIPT_INIT_STATUS` (`executionStatus`),
  KEY `IDX_FG_SCRIPT_INIT_ADD` (`tenantId`, `addTime`)
) ENGINE=InnoDB COMMENT='脚本初始化记录';
