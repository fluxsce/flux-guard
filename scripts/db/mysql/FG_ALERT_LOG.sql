-- 预警日志。功能模块写入一行，发送结果回写在同一行。不保存各功能的指标和阈值。
CREATE TABLE IF NOT EXISTS `FG_ALERT_LOG` (
  `tenantId` VARCHAR(32) NOT NULL COMMENT '租户ID，联合主键',
  `alertLogId` VARCHAR(32) NOT NULL COMMENT '预警日志ID，联合主键',
  `alertLevel` VARCHAR(20) NOT NULL COMMENT '级别：info、warn、critical',
  `alertType` VARCHAR(100) NOT NULL COMMENT '类型，由功能模块自定义',
  `sceneCode` VARCHAR(16) NOT NULL COMMENT '场景：fire、resolve、escalate、test',
  `alertTitle` VARCHAR(500) NOT NULL COMMENT '标题',
  `alertContent` TEXT DEFAULT NULL COMMENT '内容',
  `alertTimestamp` DATETIME NOT NULL COMMENT '预警时间',
  `channelId` VARCHAR(32) DEFAULT NULL COMMENT '渠道ID',
  `sendStatus` VARCHAR(20) NOT NULL DEFAULT 'pending' COMMENT '发送状态：pending、ok、fail',
  `sendTime` DATETIME DEFAULT NULL COMMENT '发送时间',
  `sendResult` TEXT DEFAULT NULL COMMENT '发送结果，JSON',
  `sendError` VARCHAR(500) DEFAULT NULL COMMENT '发送错误',
  `failCount` INT NOT NULL DEFAULT 0 COMMENT '失败次数',
  `alertExtra` TEXT DEFAULT NULL COMMENT '扩展数据，JSON',
  `addTime` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `addWho` VARCHAR(32) NOT NULL COMMENT '创建人ID',
  `editTime` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '最后修改时间',
  `editWho` VARCHAR(32) NOT NULL COMMENT '最后修改人ID',
  `oprSeqFlag` VARCHAR(32) NOT NULL COMMENT '操作序列标识',
  `currentVersion` INT NOT NULL DEFAULT 1 COMMENT '当前版本号',
  `activeFlag` VARCHAR(1) NOT NULL DEFAULT 'Y' COMMENT '活动状态标记(N非活动,Y活动)',
  `noteText` VARCHAR(500) DEFAULT NULL COMMENT '备注信息',
  `extProperty` TEXT DEFAULT NULL COMMENT '扩展属性，JSON格式',
  `reserved1` VARCHAR(64) DEFAULT NULL COMMENT '预留字段1',
  `reserved2` VARCHAR(64) DEFAULT NULL COMMENT '预留字段2',
  `reserved3` VARCHAR(100) DEFAULT NULL COMMENT '预留字段3',
  `reserved4` VARCHAR(100) DEFAULT NULL COMMENT '预留字段4',
  `reserved5` VARCHAR(255) DEFAULT NULL COMMENT '预留字段5',
  PRIMARY KEY (`tenantId`, `alertLogId`),
  KEY `IDX_FG_ALERT_LOG_SEND` (`tenantId`, `sendStatus`, `alertTimestamp`),
  KEY `IDX_FG_ALERT_LOG_TIME` (`tenantId`, `alertTimestamp`),
  KEY `IDX_FG_ALERT_LOG_ADD` (`tenantId`, `addTime`)
) ENGINE=InnoDB COMMENT='预警日志';
