-- Redis 采集记录。每次拨号只插入。
CREATE TABLE IF NOT EXISTS `FG_REDIS_METRIC` (
  `tenantId` VARCHAR(32) NOT NULL COMMENT '租户ID，联合主键',
  `pointId` VARCHAR(32) NOT NULL COMMENT '记录ID，联合主键',
  `componentId` VARCHAR(32) NOT NULL COMMENT '连接ID',
  `upFlag` VARCHAR(1) NOT NULL DEFAULT 'N' COMMENT '连通标记(Y连通,N不通)',
  `versionText` VARCHAR(64) DEFAULT NULL COMMENT '版本',
  `roleName` VARCHAR(32) DEFAULT NULL COMMENT '角色',
  `errorText` VARCHAR(100) DEFAULT NULL COMMENT '失败说明',
  `summaryText` VARCHAR(100) DEFAULT NULL COMMENT '摘要',
  `observedTime` DATETIME NOT NULL COMMENT '观测时间',
  `usedMemoryBytes` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '已用内存，字节',
  `connectedClients` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '连接数',
  `opsPerSec` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '每秒操作',
  `hitRate` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '命中率，百分比',
  `connectedSlaves` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '从节点',
  `knownNodes` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '节点数',
  `failSlots` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '失败槽',
  `memFragmentation` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '内存碎片率',
  `keyCount` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '键数量',
  `slowlogLen` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '慢操作条数',
  `uptimeSec` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '运行秒数',
  `maxMemoryBytes` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '内存上限，字节。0 表示未设 maxmemory',
  `memUsagePercent` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '已用占上限的百分比。未设上限时为 -1',
  `usedMemoryPeakBytes` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '内存峰值，字节',
  `blockedClients` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '阻塞中的客户端',
  `netInKbps` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '入站，KB/s',
  `netOutKbps` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '出站，KB/s',
  `replicaLagSec` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '复制延迟秒。无从节点或未知为 -1',
  `masterLinkDown` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '从节点看主链路：1 断开，0 正常，-1 不适用',
  `rdbOk` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '最近一次 RDB：1 成功，0 失败，-1 未知',
  `aofOk` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '最近一次 AOF：1 成功，0 失败，-1 未开启',
  `evictedPerSec` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '区间内每秒淘汰键',
  `expiredPerSec` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '区间内每秒过期键',
  `rejectedPerSec` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '区间内每秒拒绝连接',
  `keyspaceHits` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '累计命中，用于计算区间命中率',
  `keyspaceMisses` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '累计未命中',
  `evictedKeys` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '累计淘汰键',
  `expiredKeys` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '累计过期键',
  `rejectedConnections` DECIMAL(20, 3) NOT NULL DEFAULT 0 COMMENT '累计拒绝连接',
  `addTime` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `addWho` VARCHAR(32) NOT NULL COMMENT '创建人ID',
  `editTime` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '最后修改时间',
  `editWho` VARCHAR(32) NOT NULL COMMENT '最后修改人ID',
  `oprSeqFlag` VARCHAR(32) NOT NULL COMMENT '操作序列标识',
  `currentVersion` INT NOT NULL DEFAULT 1 COMMENT '当前版本号',
  `activeFlag` VARCHAR(1) NOT NULL DEFAULT 'Y' COMMENT '活动状态标记(N非活动,Y活动)',
  `noteText` VARCHAR(500) DEFAULT NULL COMMENT '备注信息',
  `extProperty` TEXT DEFAULT NULL COMMENT '扩展属性，JSON格式',
  `reserved1` VARCHAR(64) DEFAULT NULL COMMENT '预留字段1',
  `reserved2` VARCHAR(64) DEFAULT NULL COMMENT '预留字段2',
  `reserved3` VARCHAR(100) DEFAULT NULL COMMENT '预留字段3',
  `reserved4` VARCHAR(100) DEFAULT NULL COMMENT '预留字段4',
  `reserved5` VARCHAR(255) DEFAULT NULL COMMENT '预留字段5',
  PRIMARY KEY (`tenantId`, `pointId`),
  KEY `IDX_FG_REDIS_METRIC_TIME` (`tenantId`, `componentId`, `observedTime`),
  KEY `IDX_FG_REDIS_METRIC_ADD` (`tenantId`, `addTime`)
) ENGINE=InnoDB COMMENT='Redis采集记录表';
