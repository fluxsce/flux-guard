CREATE TABLE IF NOT EXISTS `FG_JOB` (
  `tenantId` VARCHAR(32) NOT NULL COMMENT '租户ID，联合主键',
  `jobCode` VARCHAR(64) NOT NULL COMMENT '任务编码，联合主键',
  `title` VARCHAR(100) NOT NULL COMMENT '任务标题',
  `enabledFlag` VARCHAR(1) NOT NULL DEFAULT 'Y' COMMENT '是否启用：Y/N',
  `lastTrigger` VARCHAR(16) DEFAULT NULL COMMENT '最近触发：schedule/manual/api',
  `lastStart` DATETIME DEFAULT NULL COMMENT '最近开始时间',
  `lastEnd` DATETIME DEFAULT NULL COMMENT '最近结束时间',
  `nextStart` DATETIME DEFAULT NULL COMMENT '下一次执行开始时间。手动、停用或没有后续时为空',
  `lastDurationMs` BIGINT NOT NULL DEFAULT 0 COMMENT '最近耗时毫秒',
  `lastOk` VARCHAR(1) NOT NULL DEFAULT 'N' COMMENT '最近是否成功：Y/N',
  `lastResult` TEXT DEFAULT NULL COMMENT '最近结果 JSON',
  `lastError` TEXT DEFAULT NULL COMMENT '最近错误',
  `ranFlag` VARCHAR(1) NOT NULL DEFAULT 'N' COMMENT '是否执行过：Y/N',
  `addTime` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `addWho` VARCHAR(32) NOT NULL COMMENT '创建人ID',
  `editTime` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '最后修改时间',
  `editWho` VARCHAR(32) NOT NULL COMMENT '最后修改人ID',
  `oprSeqFlag` VARCHAR(32) NOT NULL COMMENT '操作序列标识',
  `currentVersion` INT NOT NULL DEFAULT 1 COMMENT '当前版本号',
  `activeFlag` VARCHAR(1) NOT NULL DEFAULT 'Y' COMMENT '活动状态标记',
  `noteText` VARCHAR(500) DEFAULT NULL COMMENT '备注',
  `extProperty` TEXT DEFAULT NULL COMMENT '扩展属性',
  `reserved1` VARCHAR(64) DEFAULT NULL COMMENT '预留字段1',
  `reserved2` VARCHAR(64) DEFAULT NULL COMMENT '预留字段2',
  `reserved3` VARCHAR(100) DEFAULT NULL COMMENT '预留字段3',
  `reserved4` VARCHAR(100) DEFAULT NULL COMMENT '预留字段4',
  `reserved5` VARCHAR(255) DEFAULT NULL COMMENT '预留字段5',
  PRIMARY KEY (`tenantId`, `jobCode`),
  KEY `IDX_FG_JOB_ADD` (`tenantId`, `addTime`)
) ENGINE=InnoDB COMMENT='系统任务最近执行';
