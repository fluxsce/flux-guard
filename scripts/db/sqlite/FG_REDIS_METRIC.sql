-- Redis 采集记录。每次拨号只插入。
CREATE TABLE IF NOT EXISTS FG_REDIS_METRIC (
  tenantId TEXT NOT NULL,
  pointId TEXT NOT NULL,
  componentId TEXT NOT NULL,
  upFlag TEXT NOT NULL DEFAULT 'N',
  versionText TEXT,
  roleName TEXT,
  errorText TEXT,
  summaryText TEXT,
  observedTime TEXT NOT NULL,
  usedMemoryBytes REAL NOT NULL DEFAULT 0,
  connectedClients REAL NOT NULL DEFAULT 0,
  opsPerSec REAL NOT NULL DEFAULT 0,
  hitRate REAL NOT NULL DEFAULT 0,
  connectedSlaves REAL NOT NULL DEFAULT 0,
  knownNodes REAL NOT NULL DEFAULT 0,
  failSlots REAL NOT NULL DEFAULT 0,
  memFragmentation REAL NOT NULL DEFAULT 0,
  keyCount REAL NOT NULL DEFAULT 0,
  slowlogLen REAL NOT NULL DEFAULT 0,
  uptimeSec REAL NOT NULL DEFAULT 0,
  maxMemoryBytes REAL NOT NULL DEFAULT 0,
  memUsagePercent REAL NOT NULL DEFAULT 0,
  usedMemoryPeakBytes REAL NOT NULL DEFAULT 0,
  blockedClients REAL NOT NULL DEFAULT 0,
  netInKbps REAL NOT NULL DEFAULT 0,
  netOutKbps REAL NOT NULL DEFAULT 0,
  replicaLagSec REAL NOT NULL DEFAULT 0,
  masterLinkDown REAL NOT NULL DEFAULT 0,
  rdbOk REAL NOT NULL DEFAULT 0,
  aofOk REAL NOT NULL DEFAULT 0,
  evictedPerSec REAL NOT NULL DEFAULT 0,
  expiredPerSec REAL NOT NULL DEFAULT 0,
  rejectedPerSec REAL NOT NULL DEFAULT 0,
  keyspaceHits REAL NOT NULL DEFAULT 0,
  keyspaceMisses REAL NOT NULL DEFAULT 0,
  evictedKeys REAL NOT NULL DEFAULT 0,
  expiredKeys REAL NOT NULL DEFAULT 0,
  rejectedConnections REAL NOT NULL DEFAULT 0,
  addTime TEXT NOT NULL DEFAULT (datetime('now')),
  addWho TEXT NOT NULL,
  editTime TEXT NOT NULL DEFAULT (datetime('now')),
  editWho TEXT NOT NULL,
  oprSeqFlag TEXT NOT NULL,
  currentVersion INTEGER NOT NULL DEFAULT 1,
  activeFlag TEXT NOT NULL DEFAULT 'Y',
  noteText TEXT,
  extProperty TEXT,
  reserved1 TEXT,
  reserved2 TEXT,
  reserved3 TEXT,
  reserved4 TEXT,
  reserved5 TEXT,
  PRIMARY KEY (tenantId, pointId)
);
CREATE INDEX IF NOT EXISTS IDX_FG_REDIS_METRIC_TIME ON FG_REDIS_METRIC(tenantId, componentId, observedTime);
CREATE INDEX IF NOT EXISTS IDX_FG_REDIS_METRIC_ADD ON FG_REDIS_METRIC(tenantId, addTime);
