-- 一次应用更新。文件在 data/apprelease，每一台实例对应一行命令。
CREATE TABLE IF NOT EXISTS `FG_APP_RELEASE` (
  `releaseId` VARCHAR(32) NOT NULL COMMENT '发布ID，联合主键',
  `tenantId` VARCHAR(32) NOT NULL COMMENT '租户ID，联合主键',
  `appCode` VARCHAR(100) NOT NULL COMMENT '应用编码',
  `artifactKind` VARCHAR(16) NOT NULL COMMENT '更新种类(war,jar,static,runtime)',
  `versionText` VARCHAR(64) NOT NULL COMMENT '目标版本',
  `sha256` VARCHAR(64) NOT NULL COMMENT '文件校验和',
  `fileName` VARCHAR(255) NOT NULL COMMENT '原始文件名',
  `addTime` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `addWho` VARCHAR(32) NOT NULL COMMENT '创建人ID',
  `editTime` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '最后修改时间',
  `editWho` VARCHAR(32) NOT NULL COMMENT '最后修改人ID',
  `oprSeqFlag` VARCHAR(32) NOT NULL COMMENT '操作序列标识',
  `currentVersion` INT NOT NULL DEFAULT 1 COMMENT '当前版本号',
  `activeFlag` VARCHAR(1) NOT NULL DEFAULT 'Y' COMMENT '活动状态标记(N非活动,Y活动)',
  `noteText` VARCHAR(500) DEFAULT NULL COMMENT '备注信息',
  `extProperty` TEXT DEFAULT NULL COMMENT '扩展属性，JSON格式',
  `reserved1` VARCHAR(64) DEFAULT NULL COMMENT '预留字段1',
  `reserved2` VARCHAR(64) DEFAULT NULL COMMENT '预留字段2',
  `reserved3` VARCHAR(100) DEFAULT NULL COMMENT '预留字段3',
  `reserved4` VARCHAR(100) DEFAULT NULL COMMENT '预留字段4',
  `reserved5` VARCHAR(255) DEFAULT NULL COMMENT '预留字段5',
  PRIMARY KEY (`tenantId`, `releaseId`),
  KEY `IDX_FG_APP_RELEASE_ADD` (`tenantId`, `addTime`)
) ENGINE=InnoDB COMMENT='应用发布';

CREATE TABLE IF NOT EXISTS `FG_APP_RELEASE_ITEM` (
  `commandId` VARCHAR(32) NOT NULL COMMENT '命令ID，联合主键',
  `tenantId` VARCHAR(32) NOT NULL COMMENT '租户ID，联合主键',
  `releaseId` VARCHAR(32) NOT NULL COMMENT '发布ID',
  `instId` VARCHAR(32) NOT NULL COMMENT '实例ID',
  `agentId` VARCHAR(32) NOT NULL COMMENT '应用侧代理ID',
  `addTime` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `addWho` VARCHAR(32) NOT NULL COMMENT '创建人ID',
  `editTime` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '最后修改时间',
  `editWho` VARCHAR(32) NOT NULL COMMENT '最后修改人ID',
  `oprSeqFlag` VARCHAR(32) NOT NULL COMMENT '操作序列标识',
  `currentVersion` INT NOT NULL DEFAULT 1 COMMENT '当前版本号',
  `activeFlag` VARCHAR(1) NOT NULL DEFAULT 'Y' COMMENT '活动状态标记(N非活动,Y活动)',
  `noteText` VARCHAR(500) DEFAULT NULL COMMENT '备注信息',
  `extProperty` TEXT DEFAULT NULL COMMENT '扩展属性，JSON格式',
  `reserved1` VARCHAR(64) DEFAULT NULL COMMENT '预留字段1',
  `reserved2` VARCHAR(64) DEFAULT NULL COMMENT '预留字段2',
  `reserved3` VARCHAR(100) DEFAULT NULL COMMENT '预留字段3',
  `reserved4` VARCHAR(100) DEFAULT NULL COMMENT '预留字段4',
  `reserved5` VARCHAR(255) DEFAULT NULL COMMENT '预留字段5',
  PRIMARY KEY (`tenantId`, `commandId`),
  KEY `IDX_FG_APP_RELEASE_ITEM_REL` (`tenantId`, `releaseId`),
  KEY `IDX_FG_APP_RELEASE_ITEM_ADD` (`tenantId`, `addTime`)
) ENGINE=InnoDB COMMENT='应用发布目标';
