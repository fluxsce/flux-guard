-- scopeValue 由应用解释。不要把 filterCondition 拼进 SQL。
CREATE TABLE IF NOT EXISTS `FG_AUTH_DATA_PERMISSION` (
  `dataPermissionId` VARCHAR(32) NOT NULL COMMENT '数据权限ID，联合主键',
  `tenantId` VARCHAR(32) NOT NULL COMMENT '租户ID，联合主键',
  `userId` VARCHAR(32) DEFAULT NULL COMMENT '用户ID，空表示角色级权限',
  `roleId` VARCHAR(32) DEFAULT NULL COMMENT '角色ID，空表示用户级权限',
  `resourceType` VARCHAR(50) NOT NULL COMMENT '资源类型(TABLE数据表,API接口,MODULE模块)',
  `resourceCode` VARCHAR(100) NOT NULL COMMENT '资源编码',
  `scopeValue` TEXT DEFAULT NULL COMMENT '权限范围，JSON',
  `filterCondition` TEXT DEFAULT NULL COMMENT '保留列。应用不得把它拼进 SQL',
  `columnPermissions` TEXT DEFAULT NULL COMMENT '字段权限，JSON',
  `operationPermissions` VARCHAR(50) DEFAULT 'read' COMMENT '操作权限(read只读,write读写,delete删除)',
  `effectiveTime` DATETIME DEFAULT NULL COMMENT '生效时间',
  `expireTime` DATETIME DEFAULT NULL COMMENT '过期时间',
  `addTime` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `addWho` VARCHAR(32) NOT NULL COMMENT '创建人ID',
  `editTime` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '最后修改时间',
  `editWho` VARCHAR(32) NOT NULL COMMENT '最后修改人ID',
  `oprSeqFlag` VARCHAR(32) NOT NULL COMMENT '操作序列标识',
  `currentVersion` INT NOT NULL DEFAULT 1 COMMENT '当前版本号',
  `activeFlag` VARCHAR(1) NOT NULL DEFAULT 'Y' COMMENT '活动状态标记(N非活动,Y活动)',
  `noteText` VARCHAR(500) DEFAULT NULL COMMENT '备注信息',
  `extProperty` TEXT DEFAULT NULL COMMENT '扩展属性，JSON格式',
  `reserved1` VARCHAR(64) DEFAULT NULL COMMENT '预留字段1',
  `reserved2` VARCHAR(64) DEFAULT NULL COMMENT '预留字段2',
  `reserved3` VARCHAR(100) DEFAULT NULL COMMENT '预留字段3',
  `reserved4` VARCHAR(100) DEFAULT NULL COMMENT '预留字段4',
  `reserved5` VARCHAR(255) DEFAULT NULL COMMENT '预留字段5',
  PRIMARY KEY (`tenantId`, `dataPermissionId`),
  KEY `IDX_FG_DATA_PERM_ROLE` (`tenantId`, `roleId`),
  KEY `IDX_FG_DATA_PERM_RES` (`resourceType`, `resourceCode`),
  KEY `IDX_FG_AUTH_DATA_PERMISSION_ADD` (`tenantId`, `addTime`)
) ENGINE=InnoDB COMMENT='数据权限表';
