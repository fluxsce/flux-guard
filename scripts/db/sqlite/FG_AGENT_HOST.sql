-- 一台主机代理的当前身份。每次上报更新同一行。曲线在分类记录表里只插入。
CREATE TABLE IF NOT EXISTS FG_AGENT_HOST (
  agentId TEXT NOT NULL,
  tenantId TEXT NOT NULL,
  hostName TEXT NOT NULL,
  osName TEXT NOT NULL,
  osVersion TEXT,
  archName TEXT NOT NULL,
  cpuCount INTEGER NOT NULL DEFAULT 0,
  memTotalBytes INTEGER NOT NULL DEFAULT 0,
  ipAddress TEXT,
  bootTime TEXT,
  reportName TEXT,
  machineId TEXT,
  kernelVersion TEXT,
  agentVersion TEXT,
  ipList TEXT,
  commandAddress TEXT,
  reportedTime TEXT NOT NULL,
  cpuUsagePercent REAL NOT NULL DEFAULT 0,
  loadAvg1 REAL NOT NULL DEFAULT 0,
  memUsedPercent REAL NOT NULL DEFAULT 0,
  memUsedBytes INTEGER NOT NULL DEFAULT 0,
  diskUsedPercent REAL NOT NULL DEFAULT 0,
  diskReadBytesPerSec REAL NOT NULL DEFAULT 0,
  diskWriteBytesPerSec REAL NOT NULL DEFAULT 0,
  diskUtilPercent REAL NOT NULL DEFAULT 0,
  netReceiveBytesPerSec REAL NOT NULL DEFAULT 0,
  netTransmitBytesPerSec REAL NOT NULL DEFAULT 0,
  tcpEstablished INTEGER NOT NULL DEFAULT 0,
  tcpTimeWait INTEGER NOT NULL DEFAULT 0,
  tcpCloseWait INTEGER NOT NULL DEFAULT 0,
  fdAllocated INTEGER NOT NULL DEFAULT 0,
  fdUsedPercent REAL NOT NULL DEFAULT 0,
  procCount INTEGER NOT NULL DEFAULT 0,
  zombieCount INTEGER NOT NULL DEFAULT 0,
  addTime TEXT NOT NULL DEFAULT (datetime('now')),
  addWho TEXT NOT NULL,
  editTime TEXT NOT NULL DEFAULT (datetime('now')),
  editWho TEXT NOT NULL,
  oprSeqFlag TEXT NOT NULL,
  currentVersion INTEGER NOT NULL DEFAULT 1,
  activeFlag TEXT NOT NULL DEFAULT 'Y',
  noteText TEXT,
  extProperty TEXT,
  reserved1 TEXT,
  reserved2 TEXT,
  reserved3 TEXT,
  reserved4 TEXT,
  reserved5 TEXT,
  PRIMARY KEY (tenantId, agentId)
);
CREATE INDEX IF NOT EXISTS IDX_FG_AGENT_HOST_NAME ON FG_AGENT_HOST(tenantId, hostName);
CREATE INDEX IF NOT EXISTS IDX_FG_AGENT_HOST_ADD ON FG_AGENT_HOST(tenantId, addTime);
