-- Kafka 采集记录。每次拨号只插入。
CREATE TABLE IF NOT EXISTS FG_KAFKA_METRIC (
  tenantId TEXT NOT NULL,
  pointId TEXT NOT NULL,
  componentId TEXT NOT NULL,
  upFlag TEXT NOT NULL DEFAULT 'N',
  versionText TEXT,
  roleName TEXT,
  errorText TEXT,
  summaryText TEXT,
  observedTime TEXT NOT NULL,
  brokerCount REAL NOT NULL DEFAULT 0,
  offlinePartitions REAL NOT NULL DEFAULT 0,
  underReplicated REAL NOT NULL DEFAULT 0,
  topicCount REAL NOT NULL DEFAULT 0,
  groupCount REAL NOT NULL DEFAULT 0,
  maxLag REAL NOT NULL DEFAULT 0,
  addTime TEXT NOT NULL DEFAULT (datetime('now')),
  addWho TEXT NOT NULL,
  editTime TEXT NOT NULL DEFAULT (datetime('now')),
  editWho TEXT NOT NULL,
  oprSeqFlag TEXT NOT NULL,
  currentVersion INTEGER NOT NULL DEFAULT 1,
  activeFlag TEXT NOT NULL DEFAULT 'Y',
  noteText TEXT,
  extProperty TEXT,
  reserved1 TEXT,
  reserved2 TEXT,
  reserved3 TEXT,
  reserved4 TEXT,
  reserved5 TEXT,
  PRIMARY KEY (tenantId, pointId)
);
CREATE INDEX IF NOT EXISTS IDX_FG_KAFKA_METRIC_TIME ON FG_KAFKA_METRIC(tenantId, componentId, observedTime);
CREATE INDEX IF NOT EXISTS IDX_FG_KAFKA_METRIC_ADD ON FG_KAFKA_METRIC(tenantId, addTime);
